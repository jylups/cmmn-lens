// Writes THIRD_PARTY_NOTICES.md: the name, version, license and license text
// of every package whose code or files the server package carries, either
// bundled into dist/server.mjs or public/build/editor.js (from esbuild's lists
// of inputs) or copied into public/vendor (the viewer bundle, its styles and
// font, the Flowable descriptor).

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';

const require = createRequire(import.meta.url);

/** Packages whose files are copied into public/vendor as they are (scripts/build.mjs). */
const SERVED = ['@jylups/cmmn-js', 'flowable-cmmn-moddle', 'cmmn-font'];

/** The package folder a file in node_modules belongs to: the innermost `node_modules/<name>`. */
function packageDirOf(file) {
  const match = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(file);

  return match ? match[1] : null;
}

async function licenseText(dir) {
  const names = await readdir(dir).catch(() => []);
  // LICENSE, LICENSE.md, LICENSE-MIT.txt, COPYING …
  const file = names.find(name => /^(licen[cs]e|copying)([-.][\w.-]*)?$/i.test(name));

  return file ? (await readFile(join(dir, file), 'utf8')).trim() : null;
}

/**
 * @param {object} options
 * @param {string} options.root the server package's folder
 * @param {Record<string, unknown>} options.inputs esbuild's metafile inputs
 * @param {string} options.out the notices file to write
 */
export async function writeNotices({ root, inputs, out }) {
  const dirs = new Set();

  // folders inside a package that carry a license of their own, such as code
  // a package took from another project: package folder → { folder: text }
  const embedded = new Map();
  const seen = new Set();

  for (const file of Object.keys(inputs)) {
    const dir = packageDirOf(file);

    if (!dir) {
      continue;
    }

    dirs.add(join(root, dir));

    const folder = dirname(file);

    if (folder !== dir && !seen.has(folder)) {
      seen.add(folder);

      const text = await licenseText(join(root, folder));

      if (text) {
        const own = embedded.get(join(root, dir)) ?? {};

        own[relative(dir, folder)] = text;
        embedded.set(join(root, dir), own);
      }
    }
  }

  for (const name of SERVED) {
    dirs.add(dirname(require.resolve(`${name}/package.json`, { paths: [root] })));
  }

  const packages = [];

  for (const dir of dirs) {
    const manifest = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));

    packages.push({
      name: manifest.name,
      version: manifest.version,
      license: manifest.license ?? manifest.licenses?.map(entry => entry.type).join(' OR ') ?? 'unknown',
      author: typeof manifest.author === 'string' ? manifest.author : manifest.author?.name,
      text: await licenseText(dir),
      embedded: embedded.get(dir) ?? {}
    });
  }

  // one entry per name and version, sorted
  const unique = [...new Map(packages.map(entry => [`${entry.name}@${entry.version}`, entry])).values()]
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

  const lines = [
    '# Third-party notices',
    '',
    'The cmmn-lens server package includes code and files from these packages, bundled into',
    '`dist/server.mjs` or `public/build/editor.js`, or copied into `public/vendor`. Each is listed',
    'with its version, its license as its `package.json` declares it, and its license file as it ships.',
    '',
    'Generated by `server/scripts/notices.mjs` during `npm run build`; do not edit by hand.',
    '',
    '| Package | Version | License |',
    '|---|---|---|',
    ...unique.map(entry => `| ${entry.name} | ${entry.version} | ${entry.license} |`),
    ''
  ];

  for (const entry of unique) {
    lines.push(`## ${entry.name} ${entry.version}`, '', `License: ${entry.license}`, '');
    lines.push(entry.text
      ? ['```', entry.text, '```'].join('\n')
      : `_The package ships no license file; its package.json declares the license ${entry.license}` +
        `${entry.author ? ` and the author ${entry.author}` : ''}._`, '');

    for (const [folder, text] of Object.entries(entry.embedded)) {
      lines.push(`The package's \`${folder}\` folder has a license of its own:`, '', ['```', text, '```'].join('\n'), '');
    }
  }

  await writeFile(out, lines.join('\n'));

  return { count: unique.length, file: relative(root, out) };
}
